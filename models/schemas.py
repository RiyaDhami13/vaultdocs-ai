"""Pydantic models and resilient parser for structured contract-audit output."""

import json
import re
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class RiskFinding(BaseModel):
    """A single contract risk finding returned by the local model."""

    model_config = ConfigDict(extra="ignore")

    category: str = Field(default="Contract Risk", min_length=1)
    priority: str = Field(default="Medium", min_length=1)
    finding: str = Field(default="Potential risk or ambiguity identified.", min_length=1)
    evidence_section: str = Field(
        default="Page 1",
        description='Citation in the form "Page N - exact excerpt: ..."',
    )
    reason: str = Field(
        default="Terms may create unbalanced obligations, commercial liability, or ambiguity.",
        min_length=1,
    )
    action_question: str = Field(
        default="Can this clause be amended, capped, or clarified with the counterparty?",
        min_length=1,
    )


class AuditReport(BaseModel):
    """The complete structured audit report."""

    model_config = ConfigDict(extra="ignore")

    summary: str = Field(
        default="Contract risk screening completed.",
        min_length=1,
    )
    findings: List[RiskFinding] = Field(default_factory=list)


def _repair_and_parse_json(raw: str) -> Dict[str, Any]:
    """Parse JSON with auto-repair for truncated output, unclosed brackets, and trailing commas."""
    # 1. Direct parse attempt
    try:
        parsed = json.loads(raw)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass

    text = raw.strip()

    # 2. Repair if truncated inside "findings": [ ...
    # Locate last closed finding '}' and close array + object
    findings_start = text.find('"findings"')
    if findings_start != -1:
        bracket_start = text.find("[", findings_start)
        if bracket_start != -1:
            last_item_end = text.rfind("}")
            if last_item_end > bracket_start:
                candidate = text[: last_item_end + 1].rstrip(", \r\n\t") + "\n  ]\n}"
                try:
                    parsed = json.loads(candidate)
                    if isinstance(parsed, dict):
                        return parsed
                except json.JSONDecodeError:
                    pass

    # 3. Bracket-balancing repair
    stack = []
    in_string = False
    escape = False
    cleaned_chars = []

    for char in text:
        if escape:
            escape = False
            cleaned_chars.append(char)
            continue
        if char == "\\":
            escape = True
            cleaned_chars.append(char)
            continue
        if char == '"':
            in_string = not in_string
            cleaned_chars.append(char)
            continue
        if not in_string:
            if char in "{[":
                stack.append(char)
            elif char in "}]":
                if stack:
                    stack.pop()
        cleaned_chars.append(char)

    fixed = "".join(cleaned_chars).rstrip(", \r\n\t")
    if in_string:
        fixed += '"'

    while stack:
        open_b = stack.pop()
        if open_b == "{":
            fixed += "}"
        elif open_b == "[":
            fixed += "]"

    try:
        parsed = json.loads(fixed)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass

    # 4. Fallback: Extract completed finding objects using regex
    findings = []
    finding_matches = re.finditer(r'\{[^{}]*"category"[^{}]*\}', text, re.DOTALL)
    for m in finding_matches:
        try:
            f_obj = json.loads(m.group(0))
            if isinstance(f_obj, dict):
                findings.append(f_obj)
        except Exception:
            pass

    return {
        "summary": "Contract risk screening completed (findings recovered).",
        "findings": findings,
    }


def parse_audit_report(raw_text: str) -> AuditReport:
    """Robustly parse an AuditReport from LLM output.
    
    Handles markdown fences, truncated JSON, unclosed quotes/brackets,
    synonym field keys, and missing non-critical fields.
    """
    if not raw_text or not raw_text.strip():
        return AuditReport(summary="No findings generated by the local model.", findings=[])

    cleaned = raw_text.strip()

    # 1. Strip markdown code blocks (```json ... ``` or ``` ... ```)
    if "```" in cleaned:
        match = re.search(r"```(?:json)?\s*([\s\S]*?)(?:```|$)", cleaned, re.IGNORECASE)
        if match:
            cleaned = match.group(1).strip()
        else:
            cleaned = re.sub(r"```[a-zA-Z]*", "", cleaned).replace("```", "").strip()

    # 2. Extract outermost JSON block { ...
    first_brace = cleaned.find("{")
    if first_brace != -1:
        cleaned = cleaned[first_brace:]

    # 3. Parse with auto-repair
    data = _repair_and_parse_json(cleaned)

    # 4. Normalize field synonyms if parsed into a dict
    if isinstance(data, dict):
        if "summary" not in data:
            data["summary"] = data.get("overview") or data.get("analysis") or "Contract risk audit summary."

        raw_findings = data.get("findings")
        if raw_findings is None:
            raw_findings = data.get("risks") or data.get("clauses") or data.get("issues") or []

        if isinstance(raw_findings, list):
            normalized_findings = []
            for item in raw_findings:
                if isinstance(item, dict):
                    f_text = str(item.get("finding") or item.get("title") or item.get("description") or item.get("issue") or item.get("clause") or "")
                    
                    # Skip empty or meaningless placeholder findings
                    if not f_text.strip() or f_text.strip().lower() in ["none", "n/a", "no risk"]:
                        continue

                    f_item: Dict[str, Any] = {}
                    f_item["category"] = item.get("category") or item.get("type") or item.get("clause_type") or "Contract Risk"
                    f_item["priority"] = str(item.get("priority") or item.get("severity") or item.get("risk_level") or "Medium").capitalize()
                    f_item["finding"] = f_text

                    # Normalize evidence / quote / page citation
                    evidence = item.get("evidence_section") or item.get("evidence") or item.get("quote") or item.get("excerpt") or ""
                    page_num = item.get("page") or item.get("page_number")
                    if page_num and str(page_num) not in str(evidence):
                        evidence = f"Page {page_num} - exact excerpt: \"{evidence}\"" if evidence else f"Page {page_num}"
                    f_item["evidence_section"] = str(evidence) if evidence else "Page 1"

                    f_item["reason"] = item.get("reason") or item.get("why") or item.get("impact") or item.get("explanation") or "Terms may create unbalanced obligations or liability."
                    f_item["action_question"] = item.get("action_question") or item.get("question") or item.get("action") or item.get("recommendation") or item.get("suggested_move") or "Can this clause be amended or capped?"

                    normalized_findings.append(f_item)
            data["findings"] = normalized_findings

    return AuditReport.model_validate(data)
